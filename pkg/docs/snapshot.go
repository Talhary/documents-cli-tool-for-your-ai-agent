// SnapshotDOCX renders a visual preview of a DOCX file to a PNG image.
func SnapshotDOCX(docxPath, outPNGPath string) error {
	mdContent, err := DOCXToMarkdown(docxPath)
	if err != nil {
		return fmt.Errorf("failed reading docx for snapshot: %w", err)
	}

	width := 800
	height := 1100
	img := image.NewRGBA(image.Rect(0, 0, width, height))

	// Background: clean white
	draw.Draw(img, img.Bounds(), &image.Uniform{color.RGBA{255, 255, 255, 255}}, image.Point{}, draw.Src)

	// Document border
	borderColor := color.RGBA{220, 224, 230, 255}
	drawRect(img, 20, 20, width-40, height-40, borderColor, 2)

	// Header banner
	headerColor := color.RGBA{46, 116, 181, 255} // Word Blue
	fillRect(img, 22, 22, width-44, 10, headerColor)

	// Margins
	startX := 50
	curY := 60
	maxY := height - 60
	lineHeight := 20

	lines := strings.Split(mdContent, "\n")
	for _, rawLine := range lines {
		if curY >= maxY {
			break
		}

		line := strings.TrimSpace(rawLine)
		if line == "" {
			curY += lineHeight / 2
			continue
		}

		if strings.HasPrefix(line, "# ") {
			// Heading 1
			title := strings.TrimPrefix(line, "# ")
			drawString(img, startX, curY, title, color.RGBA{46, 116, 181, 255}, 2)
			curY += lineHeight * 2
			// Divider line
			fillRect(img, startX, curY-8, width-100, 2, borderColor)
		} else if strings.HasPrefix(line, "## ") {
			// Heading 2
			sub := strings.TrimPrefix(line, "## ")
			drawString(img, startX, curY, sub, color.RGBA{31, 78, 121, 255}, 1)
			curY += int(float64(lineHeight) * 1.5)
		} else if strings.HasPrefix(line, "| ") {
			// Table row
			cells := strings.Split(strings.Trim(line, "|"), "|")
			cellWidth := (width - 120) / len(cells)
			for cIdx, c := range cells {
				cx := startX + (cIdx * cellWidth)
				drawRect(img, cx, curY-2, cellWidth, lineHeight+4, borderColor, 1)
				drawString(img, cx+6, curY+2, strings.TrimSpace(c), color.RGBA{40, 40, 40, 255}, 1)
			}
			curY += lineHeight + 6
		} else {
			// Paragraph
			// Simple word wrapping
			wrapped := wrapText(line, 80)
			for _, wLine := range wrapped {
				if curY >= maxY {
					break
				}
				drawString(img, startX, curY, wLine, color.RGBA{50, 50, 50, 255}, 1)
				curY += lineHeight
			}
		}
	}

	outFile, err := os.Create(outPNGPath)
	if err != nil {
		return fmt.Errorf("failed to create snapshot file %s: %w", outPNGPath, err)
	}
	defer outFile.Close()

	return png.Encode(outFile, img)
}

func drawRect(img *image.RGBA, x, y, w, h int, col color.Color, thickness int) {
	for t := 0; t < thickness; t++ {
		// Top and bottom
		for i := x; i < x+w; i++ {
			img.Set(i, y+t, col)
			img.Set(i, y+h-1-t, col)
		}
		// Left and right
		for j := y; j < y+h; j++ {
			img.Set(x+t, j, col)
			img.Set(x+w-1-t, j, col)
		}
	}
}

func fillRect(img *image.RGBA, x, y, w, h int, col color.Color) {
	for i := x; i < x+w; i++ {
		for j := y; j < y+h; j++ {
			img.Set(i, j, col)
		}
	}
}

func wrapText(text string, maxChars int) []string {
	var lines []string
	words := strings.Fields(text)
	var cur strings.Builder

	for _, w := range words {
		if cur.Len()+len(w)+1 > maxChars {
			lines = append(lines, cur.String())
			cur.Reset()
		}
		if cur.Len() > 0 {
			cur.WriteString(" ")
		}
		cur.WriteString(w)
	}
	if cur.Len() > 0 {
		lines = append(lines, cur.String())
	}
	return lines
}

// drawString renders readable ASCII bitmap characters onto an RGBA canvas.
func drawString(img *image.RGBA, x, y int, text string, col color.RGBA, scale int) {
	if scale < 1 {
		scale = 1
	}
	curX := x
	for _, r := range text {
		glyph, ok := basicFont[r]
		if !ok {
			glyph = basicFont['?']
		}
		for gy, row := range glyph {
			for gx := 0; gx < 5; gx++ {
				if (row & (1 << (4 - gx))) != 0 {
					for sx := 0; sx < scale; sx++ {
						for sy := 0; sy < scale; sy++ {
							img.Set(curX+gx*scale+sx, y+gy*scale+sy, col)
						}
					}
				}
			}
		}
		curX += (5 + 1) * scale
	}
}

