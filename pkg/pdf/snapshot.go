// SnapshotPDF renders a visual preview of a specific PDF page to a PNG image.
func SnapshotPDF(pdfPath, outPNGPath string, pageNum int) error {
	pages, err := ExtractPages(pdfPath)
	if err != nil {
		return fmt.Errorf("failed reading pdf for snapshot: %w", err)
	}

	if len(pages) == 0 {
		return fmt.Errorf("pdf contains no readable pages")
	}

	if pageNum < 1 {
		pageNum = 1
	}
	if pageNum > len(pages) {
		pageNum = len(pages)
	}

	return renderPageToPNG(pages, pageNum, outPNGPath)
}

// SnapshotAllPages renders multiple or all PDF pages into separate PNG images concurrently.
func SnapshotAllPages(pdfPath, outDirOrPattern string, fromPage, toPage int, workers int) ([]string, error) {
	pages, err := ExtractPages(pdfPath)
	if err != nil {
		return nil, fmt.Errorf("failed reading pdf for snapshot: %w", err)
	}

	total := len(pages)
	if total == 0 {
		return nil, fmt.Errorf("pdf contains no readable pages")
	}

	if fromPage < 1 {
		fromPage = 1
	}
	if toPage <= 0 || toPage > total {
		toPage = total
	}
	if fromPage > toPage {
		return nil, fmt.Errorf("invalid page range %d..%d (total %d)", fromPage, toPage, total)
	}

	baseName := strings.TrimSuffix(filepath.Base(pdfPath), filepath.Ext(pdfPath))
	baseName = regexp.MustCompile(`[^a-zA-Z0-9_\-]+`).ReplaceAllString(baseName, "_")

	isDir := !strings.HasSuffix(strings.ToLower(outDirOrPattern), ".png") || strings.HasSuffix(outDirOrPattern, "/") || strings.HasSuffix(outDirOrPattern, "\\")
	if isDir {
		_ = os.MkdirAll(outDirOrPattern, 0755)
	} else {
		_ = os.MkdirAll(filepath.Dir(outDirOrPattern), 0755)
	}

	var generatedFiles []string
	var mu sync.Mutex

	ctx := context.Background()
	pool := concurrency.NewPool(ctx, workers)

	for p := fromPage; p <= toPage; p++ {
		pNum := p
		var targetPath string
		if isDir {
			targetPath = filepath.Join(outDirOrPattern, fmt.Sprintf("%s_page_%d.png", baseName, pNum))
		} else if strings.Contains(outDirOrPattern, "%d") {
			targetPath = fmt.Sprintf(outDirOrPattern, pNum)
		} else {
			targetPath = outDirOrPattern
		}

		pool.Submit(func(c context.Context) error {
			err := renderPageToPNG(pages, pNum, targetPath)
			if err == nil {
				mu.Lock()
				generatedFiles = append(generatedFiles, filepath.ToSlash(targetPath))
				mu.Unlock()
			}
			return err
		})
	}

	pool.Close()
	return generatedFiles, nil
}

func renderPageToPNG(pages []string, pageNum int, outPNGPath string) error {

	pageText := pages[pageNum-1]

	width := 800
	height := 1100
	img := image.NewRGBA(image.Rect(0, 0, width, height))

	// Clean white page background
	draw.Draw(img, img.Bounds(), &image.Uniform{color.RGBA{255, 255, 255, 255}}, image.Point{}, draw.Src)

	// PDF page border
	borderColor := color.RGBA{225, 228, 232, 255}
	drawRect(img, 20, 20, width-40, height-40, borderColor, 2)

	// PDF Red header accent
	headerColor := color.RGBA{217, 48, 37, 255} // PDF Red
	fillRect(img, 22, 22, width-44, 8, headerColor)

	// Page footer
	footerText := fmt.Sprintf("Page %d of %d", pageNum, len(pages))
	drawString(img, width/2-30, height-35, footerText, color.RGBA{140, 140, 140, 255}, 1)

	startX := 50
	curY := 60
	maxY := height - 60
	lineHeight := 20

	lines := strings.Split(pageText, "\n")
	for _, rawLine := range lines {
		if curY >= maxY {
			break
		}
		line := strings.TrimSpace(rawLine)
		if line == "" {
			curY += lineHeight / 2
			continue
		}

		wrapped := wrapText(line, 80)
		for _, wLine := range wrapped {
			if curY >= maxY {
				break
			}
			drawString(img, startX, curY, wLine, color.RGBA{45, 45, 45, 255}, 1)
			curY += lineHeight
		}
	}

	outFile, err := os.Create(outPNGPath)
	if err != nil {
		return fmt.Errorf("failed creating snapshot file %s: %w", outPNGPath, err)
	}
	defer outFile.Close()

	return png.Encode(outFile, img)
}

func drawRect(img *image.RGBA, x, y, w, h int, col color.Color, thickness int) {
	for t := 0; t < thickness; t++ {
		for i := x; i < x+w; i++ {
			img.Set(i, y+t, col)
			img.Set(i, y+h-1-t, col)
		}
		for j := y; j < y+h; j++ {
			img.Set(x+t, j, col)
			img.Set(x+w-1-t, j, col)
		}
	}
}

func fillRect(img *image.RGBA, x, y, w, h int, col color.Color) {
	for i := x; i < x+w; i++ {
		for j := y; j < y+h; j++ {
			img.Set(i, j, col)
		}
	}
}

func wrapText(text string, maxChars int) []string {
	var lines []string
	words := strings.Fields(text)
	var cur strings.Builder

	for _, w := range words {
		if cur.Len()+len(w)+1 > maxChars {
			lines = append(lines, cur.String())
			cur.Reset()
		}
		if cur.Len() > 0 {
			cur.WriteString(" ")
		}
		cur.WriteString(w)
	}
	if cur.Len() > 0 {
		lines = append(lines, cur.String())
	}
	return lines
}

func drawString(img *image.RGBA, x, y int, text string, col color.RGBA, scale int) {
	if scale < 1 {
		scale = 1
	}
	curX := x
	for _, r := range text {
		glyph, ok := basicFont[r]
		if !ok {
			glyph = basicFont['?']
		}
		for gy, row := range glyph {
			for gx := 0; gx < 5; gx++ {
				if (row & (1 << (4 - gx))) != 0 {
					for sx := 0; sx < scale; sx++ {
						for sy := 0; sy < scale; sy++ {
							img.Set(curX+gx*scale+sx, y+gy*scale+sy, col)
						}
					}
				}
			}
		}
		curX += (5 + 1) * scale
	}
}

